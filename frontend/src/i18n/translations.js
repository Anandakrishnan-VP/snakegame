/**
 * Helper to get translated string for a given language code and key.
 * Falls back to English if key is missing in chosen language.
 */
export function getTranslation(langCode, key) {
  const langObj = translations[langCode] || translations.en;
  if (langObj && langObj[key]) {
    return langObj[key];
  }
  return translations.en[key] || key;
}
